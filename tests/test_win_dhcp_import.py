class TestSplitPoolByExclusions:
    def test_no_exclusions(self):
        assert w.split_pool_by_exclusions("10.0.0.10", "10.0.0.20", []) == [
            (w._ip2int("10.0.0.10"), w._ip2int("10.0.0.20"))
        ]

    def test_exclusion_in_the_middle_splits_into_two(self):
        segs = w.split_pool_by_exclusions("10.0.0.10", "10.0.0.20", [("10.0.0.14", "10.0.0.16")])
        assert segs == [
            (w._ip2int("10.0.0.10"), w._ip2int("10.0.0.13")),
            (w._ip2int("10.0.0.17"), w._ip2int("10.0.0.20")),
        ]

    def test_exclusion_at_the_start(self):
        segs = w.split_pool_by_exclusions("10.0.0.10", "10.0.0.20", [("10.0.0.10", "10.0.0.12")])
        assert segs == [(w._ip2int("10.0.0.13"), w._ip2int("10.0.0.20"))]

    def test_exclusion_at_the_end(self):
        segs = w.split_pool_by_exclusions("10.0.0.10", "10.0.0.20", [("10.0.0.18", "10.0.0.20")])
        assert segs == [(w._ip2int("10.0.0.10"), w._ip2int("10.0.0.17"))]

    def test_exclusion_covering_the_whole_range_yields_no_pools(self):
        segs = w.split_pool_by_exclusions("10.0.0.10", "10.0.0.20", [("10.0.0.1", "10.0.0.254")])
        assert segs == []

    def test_multiple_non_overlapping_exclusions(self):
        segs = w.split_pool_by_exclusions(
            "10.0.0.1", "10.0.0.100", [("10.0.0.10", "10.0.0.19"), ("10.0.0.50", "10.0.0.59")]
        )
        assert segs == [
            (w._ip2int("10.0.0.1"), w._ip2int("10.0.0.9")),
            (w._ip2int("10.0.0.20"), w._ip2int("10.0.0.49")),
            (w._ip2int("10.0.0.60"), w._ip2int("10.0.0.100")),
        ]


class TestCarvePool:
    def test_carves_a_pool_out_of_the_middle(self):
        segs = [(w._ip2int("10.0.0.1"), w._ip2int("10.0.0.100"))]
        new_segs, ok = w._carve_pool(segs, w._ip2int("10.0.0.40"), w._ip2int("10.0.0.50"))
        assert ok is True
        assert (w._ip2int("10.0.0.1"), w._ip2int("10.0.0.39")) in new_segs
        assert (w._ip2int("10.0.0.51"), w._ip2int("10.0.0.100")) in new_segs

    def test_refuses_a_range_spanning_two_segments(self):
        segs = [(w._ip2int("10.0.0.1"), w._ip2int("10.0.0.10")), (w._ip2int("10.0.0.20"), w._ip2int("10.0.0.30"))]
        new_segs, ok = w._carve_pool(segs, w._ip2int("10.0.0.5"), w._ip2int("10.0.0.25"))
        assert ok is False
        assert new_segs == segs

    def test_refuses_a_range_outside_every_segment(self):
        segs = [(w._ip2int("10.0.0.1"), w._ip2int("10.0.0.10"))]
        new_segs, ok = w._carve_pool(segs, w._ip2int("10.0.0.50"), w._ip2int("10.0.0.60"))
        assert ok is False
        assert new_segs == segs


