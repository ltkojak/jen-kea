# ── to_kea, end to end against the fixture ──────────────────────────────────


class TestToKea:
    SUBNET_NAMES = {
        "10.0.1.0": {"id": 10, "name": "LAN"},
        "10.0.2.0": {"id": 11, "name": "Guest WiFi"},
        "10.0.3.0": {"id": 12, "name": "Solo Subnet"},
    }
    ALL_SELECTED = {
        "scopes": {"10.0.1.0": True, "10.0.2.0": True, "10.0.3.0": True},
        "server_options": True,
    }

    def _plan(self):
        return w.parse_export(_read("windows-dhcp-export.xml"))

    def test_default_selection_only_includes_active_scopes(self):
        plan = self._plan()
        cfg, _res, declared, _report = w.to_kea(plan, None, self.SUBNET_NAMES, {"scopes": {}})
        assert 11 not in declared  # Guest WiFi is Inactive, not selected by default
        assert 10 in declared and 12 in declared

    def test_server_options_only_imported_when_selected(self):
        plan = self._plan()
        cfg, _res, _declared, _report = w.to_kea(
            plan, None, self.SUBNET_NAMES, {"scopes": {"10.0.3.0": True}, "server_options": False}
        )
        assert "option-data" not in cfg["Dhcp4"] or cfg["Dhcp4"]["option-data"] == []

    def test_superscope_becomes_a_shared_network_when_two_members_included(self):
        plan = self._plan()
        cfg, _res, _declared, _report = w.to_kea(plan, None, self.SUBNET_NAMES, self.ALL_SELECTED)
        nets = cfg["Dhcp4"]["shared-networks"]
        assert len(nets) == 1 and nets[0]["name"] == "HQ"
        ids_in_network = {s["id"] for s in nets[0]["subnet4"]}
        assert ids_in_network == {10, 11}

    def test_lone_superscope_member_does_not_get_a_shared_network(self):
        plan = self._plan()
        selections = {"scopes": {"10.0.1.0": True, "10.0.3.0": True}, "server_options": False}
        cfg, _res, _declared, _report = w.to_kea(plan, None, self.SUBNET_NAMES, selections)
        assert "shared-networks" not in cfg["Dhcp4"] or cfg["Dhcp4"]["shared-networks"] == []
        top_ids = {s["id"] for s in cfg["Dhcp4"].get("subnet4", [])}
        assert 10 in top_ids  # only 1 of HQ's 2 scopes selected -> no shared network

    def test_solo_subnet_is_top_level(self):
        plan = self._plan()
        cfg, _res, _declared, _report = w.to_kea(plan, None, self.SUBNET_NAMES, self.ALL_SELECTED)
        top_ids = {s["id"] for s in cfg["Dhcp4"].get("subnet4", [])}
        assert top_ids == {12}

    def test_reservations_carry_the_right_subnet_id(self):
        plan = self._plan()
        cfg, reservations, _declared, _report = w.to_kea(plan, None, self.SUBNET_NAMES, self.ALL_SELECTED)
        assert reservations == [
            {"subnet-id": 10, "hw-address": "00:11:22:33:44:55", "ip-address": "10.0.1.5", "hostname": "printer.lan"}
        ]

    def test_classless_route_121_lands_on_the_lan_subnet(self):
        plan = self._plan()
        cfg, _res, _declared, _report = w.to_kea(plan, None, self.SUBNET_NAMES, self.ALL_SELECTED)
        lan = next(s for net in cfg["Dhcp4"]["shared-networks"] for s in net["subnet4"] if s["id"] == 10)
        codes = {o["code"] for o in lan["option-data"]}
        assert 121 in codes

    def test_policy_with_ip_range_gets_a_dedicated_guarded_pool(self):
        plan = self._plan()
        cfg, _res, _declared, _report = w.to_kea(plan, None, self.SUBNET_NAMES, self.ALL_SELECTED)
        lan = next(s for net in cfg["Dhcp4"]["shared-networks"] for s in net["subnet4"] if s["id"] == 10)
        voip_pool = next(p for p in lan["pools"] if p["pool"] == "10.0.1.200 - 10.0.1.219")
        assert voip_pool.get("client-class") == "VoIP_Phones"

    def test_policy_without_ip_ranges_guards_the_whole_subnet(self):
        plan = self._plan()
        cfg, _res, _declared, _report = w.to_kea(plan, None, self.SUBNET_NAMES, self.ALL_SELECTED)
        lan = next(s for net in cfg["Dhcp4"]["shared-networks"] for s in net["subnet4"] if s["id"] == 10)
        assert lan.get("client-class") == "Guest_Devices"

    def test_disabled_policy_never_becomes_a_class(self):
        plan = self._plan()
        cfg, _res, _declared, _report = w.to_kea(plan, None, self.SUBNET_NAMES, self.ALL_SELECTED)
        names = {c["name"] for c in cfg["Dhcp4"]["client-classes"]}
        assert "Disabled_Legacy_Rule" not in names

    def test_existing_cidr_is_skipped_with_a_warning(self):
        plan = self._plan()
        existing = {"Dhcp4": {"subnet4": [{"id": 99, "subnet": "10.0.3.0/24", "pools": []}]}}
        cfg, _res, declared, report = w.to_kea(plan, existing, self.SUBNET_NAMES, self.ALL_SELECTED)
        assert 12 not in declared
        assert any("already exists" in msg for msg in report)

    def test_does_not_mutate_the_existing_config(self):
        import copy

        plan = self._plan()
        existing = {"Dhcp4": {"subnet4": []}}
        snapshot = copy.deepcopy(existing)
        w.to_kea(plan, existing, self.SUBNET_NAMES, self.ALL_SELECTED)
        assert existing == snapshot

    def test_scope_with_no_chosen_subnet_id_is_skipped(self):
        plan = self._plan()
        names = dict(self.SUBNET_NAMES)
        del names["10.0.3.0"]
        cfg, _res, declared, report = w.to_kea(plan, None, names, self.ALL_SELECTED)
        assert 12 not in declared
        assert any("no subnet id chosen" in msg for msg in report)
