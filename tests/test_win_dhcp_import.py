class TestOptionsToKea:
    def test_known_option_maps_through_the_catalog(self):
        entries, warnings = w._options_to_kea({3: "10.0.0.1"}, "ctx")
        assert warnings == []
        assert entries == [{"name": "routers", "code": 3, "space": "dhcp4", "csv-format": True, "data": "10.0.0.1"}]

