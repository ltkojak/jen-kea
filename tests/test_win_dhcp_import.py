class TestConditionToRule:
    def test_vendor_class(self):
        rule, warning = w._condition_to_rule({"type": "VendorClass", "value": "Cisco"}, "x")
        assert warning is None
        assert rule == {"field": "vendor_class", "op": "equals", "value": "Cisco"}

    def test_user_class(self):
        rule, _ = w._condition_to_rule({"type": "UserClass", "value": "guest"}, "x")
        assert rule["field"] == "user_class"

    def test_client_id(self):
        rule, _ = w._condition_to_rule({"type": "ClientId", "value": "AABBCC"}, "x")
        assert rule["field"] == "client_id"

    def test_relay_agent_information(self):
        rule, _ = w._condition_to_rule({"type": "RelayAgentInformation", "value": "circuit1"}, "x")
        assert rule["field"] == "circuit_id"

    def test_mac_address_full_no_wildcard(self):
        rule, warning = w._condition_to_rule({"type": "MACAddress", "value": "00-11-22-33-44-55"}, "x")
        assert warning is None
        assert rule == {"field": "mac", "op": "equals", "value": "00-11-22-33-44-55"}

    def test_mac_address_three_byte_wildcard_is_oui(self):
        rule, _ = w._condition_to_rule({"type": "MACAddress", "value": "00-11-22*"}, "x")
        assert rule["field"] == "mac_oui"
        assert rule["value"] == "00-11-22"

    def test_mac_address_wildcard_with_more_than_three_bytes_is_not_oui(self):
        rule, _ = w._condition_to_rule({"type": "MACAddress", "value": "00-11-22-33*"}, "x")
        assert rule["field"] == "mac"

    def test_unsupported_condition_type(self):
        rule, warning = w._condition_to_rule({"type": "Subnet", "value": "x"}, "ctx")
        assert rule is None
        assert warning and "ctx" in warning


class TestPolicyToClass:
    def _policy(self, **kw):
        defaults = {
            "name": "p",
            "enabled": True,
            "processing_order": 1,
            "condition": "AND",
            "conditions": [],
            "ip_ranges": [],
        }
        defaults.update(kw)
        return w.Policy(**defaults)

    def test_simple_equals_policy(self):
        p = self._policy(conditions=[{"type": "VendorClass", "operator": "Equals", "value": "Cisco"}])
        cls, warnings = w.policy_to_class(p, "ctx")
        assert warnings == []
        assert cls == {"name": "p", "test": "option[60].hex == 'Cisco'"}

    def test_or_combinator(self):
        p = self._policy(
            condition="OR",
            conditions=[
                {"type": "VendorClass", "operator": "Equals", "value": "Cisco"},
                {"type": "UserClass", "operator": "Equals", "value": "voip"},
            ],
        )
        cls, _ = w.policy_to_class(p, "ctx")
        assert " or " in cls["test"]

    def test_and_combinator(self):
        p = self._policy(
            condition="AND",
            conditions=[
                {"type": "VendorClass", "operator": "Equals", "value": "Cisco"},
                {"type": "UserClass", "operator": "Equals", "value": "voip"},
            ],
        )
        cls, _ = w.policy_to_class(p, "ctx")
        assert " and " in cls["test"]

    def test_not_equals_single_condition_negates(self):
        p = self._policy(conditions=[{"type": "UserClass", "operator": "NotEquals", "value": "trusted"}])
        cls, warnings = w.policy_to_class(p, "ctx")
        assert warnings == []
        assert cls["test"] == "not (option[77].hex == 'trusted')"

    def test_not_equals_multi_condition_is_refused(self):
        p = self._policy(
            conditions=[
                {"type": "UserClass", "operator": "NotEquals", "value": "trusted"},
                {"type": "VendorClass", "operator": "Equals", "value": "Cisco"},
            ]
        )
        cls, warnings = w.policy_to_class(p, "ctx")
        assert cls is None
        assert any("NotEquals" in msg for msg in warnings)

    def test_mixed_equals_and_notequals_is_refused(self):
        p = self._policy(
            conditions=[
                {"type": "UserClass", "operator": "NotEquals", "value": "trusted"},
                {"type": "VendorClass", "operator": "NotEquals", "value": "Cisco"},
            ]
        )
        # both NotEquals (2 conditions) -> refused by the single-condition rule
        cls, warnings = w.policy_to_class(p, "ctx")
        assert cls is None

    def test_disabled_policy_is_skipped(self):
        p = self._policy(enabled=False, conditions=[{"type": "VendorClass", "value": "Cisco"}])
        cls, warnings = w.policy_to_class(p, "ctx")
        assert cls is None
        assert any("disabled" in msg for msg in warnings)

    def test_no_conditions_is_skipped(self):
        p = self._policy(conditions=[])
        cls, warnings = w.policy_to_class(p, "ctx")
        assert cls is None

    def test_unsupported_condition_skips_whole_policy(self):
        p = self._policy(conditions=[{"type": "Subnet", "value": "x"}])
        cls, warnings = w.policy_to_class(p, "ctx")
        assert cls is None
        assert any("not supported" in msg for msg in warnings)

    def test_name_with_spaces_is_sanitized(self):
        p = self._policy(name="VoIP Phones", conditions=[{"type": "VendorClass", "value": "Cisco"}])
        cls, warnings = w.policy_to_class(p, "ctx")
        assert cls["name"] == "VoIP_Phones"
        assert any("sanitized" in msg for msg in warnings)

    def test_policy_options_become_class_option_data(self):
        p = self._policy(
            conditions=[{"type": "VendorClass", "value": "Cisco"}],
            ip_ranges=[],
        )
        p.options = {66: "tftp.example.com"}
        cls, _ = w.policy_to_class(p, "ctx")
        assert cls["option-data"] == [
            {"name": "tftp-server-name", "code": 66, "space": "dhcp4", "csv-format": True, "data": "tftp.example.com"}
        ]


