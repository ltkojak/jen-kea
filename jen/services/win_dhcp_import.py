def _prefix_len(mask: str) -> int:
    try:
        octets = [int(o) for o in mask.split(".")]
        bits = "".join(f"{o:08b}" for o in octets)
        return bits.count("1")
    except Exception:
        return 24


@dataclass
class MappedScope:
    """Everything one scope produced, before it's stitched into a real
    Dhcp4 config: the plain subnet4 block (pools carry no metadata of
    their own — `pool_guards` names which exact pool string, matching
    what's literally in `subnet["pools"]`, guards which class), the
    classes it wants added globally, and which of those guard the whole
    subnet vs. one specific pool."""

    subnet: dict
    classes: list[dict] = field(default_factory=list)
    pool_guards: list[tuple[str, str]] = field(default_factory=list)  # (pool string, class name)
    subnet_guards: list[str] = field(default_factory=list)  # class names
    warnings: list[str] = field(default_factory=list)


def scope_to_subnet(scope: Scope, jen_id: int) -> MappedScope:
    """Map one Scope onto a subnet4 block plus whatever classes its
    policies produce. A policy with IPRanges that fit cleanly inside one
    of the scope's own pool segments gets its own carved-out pool,
    guarded by its class; anything else (no IPRanges, or a range that
    doesn't fit a single segment) guards the whole subnet instead, with
    a warning in the latter case."""
    context = f"scope {scope.name}"
    warnings: list[str] = []

    segments = split_pool_by_exclusions(scope.start_range, scope.end_range, scope.exclusions)
    if not segments and scope.exclusions:
        warnings.append(f"{context}: exclusions cover the entire range — no pools (reservation-only subnet)")

    classes: list[dict] = []
    pool_guards: list[tuple[str, str]] = []
    subnet_guards: list[str] = []
    carved_pools: list[tuple[int, int]] = []

    for policy in sorted(scope.policies, key=lambda p: p.processing_order):
        class_dict, class_warnings = policy_to_class(policy, context)
        warnings.extend(class_warnings)
        if class_dict is None:
            continue
        classes.append(class_dict)

        carved = None
        for r_start, r_end in policy.ip_ranges:
            if not r_start or not r_end:
                continue
            want_s, want_e = _ip2int(r_start), _ip2int(r_end)
            segments, ok = _carve_pool(segments, want_s, want_e)
            if ok:
                carved = (want_s, want_e)
                break
            warnings.append(
                f"{context}: policy {policy.name!r}'s IP range {r_start}-{r_end} doesn't sit inside a single "
                f"existing pool — {class_dict['name']} attached to the whole subnet instead"
            )
        if carved is not None:
            carved_pools.append(carved)
            pool_guards.append((f"{_int2ip(carved[0])} - {_int2ip(carved[1])}", class_dict["name"]))
        else:
            subnet_guards.append(class_dict["name"])

    pools = [{"pool": f"{_int2ip(s)} - {_int2ip(e)}"} for s, e in segments + carved_pools]

    option_entries, timers, opt_warnings = _options_to_kea(scope.options, context)
    warnings.extend(opt_warnings)

    # v5.28.0 (Q24, F6) — 51/58/59 are lease timers, not option-data.
    # Windows enforces option 51 (Lease) as the client-facing lease
    # time even when it disagrees with the scope's own LeaseDuration —
    # so when they differ, 51 wins here too, with a warning explaining
    # why the imported subnet's valid-lifetime isn't what LeaseDuration
    # alone would suggest.
    valid_lifetime = scope.lease_seconds
    opt51 = timers.get("valid-lifetime")
    if opt51 is not None:
        try:
            opt51_seconds = int(opt51)
        except ValueError:
            opt51_seconds = None
        if opt51_seconds is not None and opt51_seconds != scope.lease_seconds:
            warnings.append(
                f"{context}: option 51 ({opt51_seconds}s) differs from LeaseDuration "
                f"({scope.lease_seconds}s) — option 51 wins, matching what Windows actually handed clients"
            )
            valid_lifetime = opt51_seconds

    subnet = {
        "id": jen_id,
        "subnet": f"{scope.scope_id}/{_prefix_len(scope.subnet_mask)}",
        "pools": pools,
        "valid-lifetime": valid_lifetime,
        "option-data": option_entries,
    }
    for timer_key in ("renew-timer", "rebind-timer"):
        if timer_key in timers:
            try:
                subnet[timer_key] = int(timers[timer_key])
            except ValueError:
                warnings.append(
                    f"{context}: option {58 if timer_key == 'renew-timer' else 59} value isn't a number — skipped"
                )
    return MappedScope(
        subnet=subnet, classes=classes, pool_guards=pool_guards, subnet_guards=subnet_guards, warnings=warnings
    )


# ── top-level mapping ────────────────────────────────────────────────────────


def to_kea(plan: Plan, existing_dhcp4_cfg: dict | None, subnet_names: dict, selections: dict):
    """The Plan, filtered by the review page's choices, onto a new
    Dhcp4 config. Returns (new_cfg, reservations, subnets_to_declare, report):
      * new_cfg — existing_dhcp4_cfg with the selected scopes' subnets
        (nested under a shared network when their Windows superscope has
        at least one other included member), classes, and guard
        attachments added. Never mutates the caller's dict.
      * reservations — [{"subnet-id","hw-address","ip-address","hostname"}, ...]
        ready for a reservation-add loop — these live in Kea's host DB,
        not the config file, so the route pushes them separately.
      * subnets_to_declare — {jen_id: {"name","cidr"}} for
        app_config.write_subnets_config() — merge with the EXISTING
        SUBNET_MAP yourself; this only carries the new entries.
      * report — every warning, in the order encountered, plus one
        summary line per imported scope.

    `subnet_names` is {scope_id: {"id": <jen subnet id>, "name": <friendly name>}}
    for every scope the caller wants considered (whether or not it ends
    up actually included — `selections["scopes"]` decides that).
    `selections` is {"scopes": {scope_id: bool}, "server_options": bool}.
    """
    cfg = copy.deepcopy(existing_dhcp4_cfg) if existing_dhcp4_cfg else {}
    cfg.setdefault("Dhcp4", {})
    report: list[str] = list(plan.warnings)
    reservations: list[dict] = []
    subnets_to_declare: dict[int, dict] = {}

    existing_cidrs = {s.get("subnet") for s, _sn in _view.iter_subnet4(cfg["Dhcp4"])}

    scope_selections = selections.get("scopes", {})
    included_scopes = [s for s in plan.scopes if scope_selections.get(s.scope_id, s.state.lower() == "active")]

    if selections.get("server_options") and plan.server_options:
        entries, _timers, warnings = _options_to_kea(plan.server_options, "server")
        report.extend(warnings)
        existing = cfg["Dhcp4"].setdefault("option-data", [])
        existing_codes = {e.get("code") for e in existing if isinstance(e, dict)}
        for e in entries:
            if e["code"] in existing_codes:
                report.append(f"server option {e['code']} already present at global level — kept as-is")
                continue
            existing.append(e)

    # Which scope_ids share a superscope with at least one OTHER included
    # scope — a superscope containing only one included member isn't
    # worth a shared network (nothing shares it with).
    network_for_scope: dict[str, str] = {}
    included_ids = {s.scope_id for s in included_scopes}
    for net_name, member_ids in plan.superscopes.items():
        included_members = [sid for sid in member_ids if sid in included_ids]
        if len(included_members) >= 2:
            for sid in included_members:
                network_for_scope[sid] = net_name

    for net_name in sorted(set(network_for_scope.values())):
        cfg, code = _edit.create_shared_network4(cfg, net_name)
        if code == "exists":
            report.append(f"shared network {net_name!r} already exists in Kea — reusing it")

    for scope in included_scopes:
        names = subnet_names.get(scope.scope_id) or {}
        jen_id = names.get("id")
        friendly_name = names.get("name") or scope.name
        if jen_id is None:
            report.append(f"scope {scope.name}: no subnet id chosen — skipped")
            continue

        mapped = scope_to_subnet(scope, jen_id)
        report.extend(mapped.warnings)

        if mapped.subnet["subnet"] in existing_cidrs:
            report.append(f"scope {scope.name}: CIDR {mapped.subnet['subnet']} already exists in Kea — skipped")
            continue
        existing_cidrs.add(mapped.subnet["subnet"])

        cfg, code = _edit.add_subnet4(cfg, mapped.subnet, shared_network=network_for_scope.get(scope.scope_id))
        if code != "ok":
            report.append(f"scope {scope.name}: could not add subnet {jen_id} ({code}) — skipped")
            continue

        for class_dict in mapped.classes:
            cfg, _code = _edit.upsert_class4(cfg, class_dict)

        for class_name in mapped.subnet_guards:
            cfg, code = _edit.attach_class4(cfg, class_name, "subnet", jen_id, mode="guard")
            if code != "ok":
                report.append(f"scope {scope.name}: could not attach class {class_name!r} to the subnet ({code})")

        for pool_str, class_name in mapped.pool_guards:
            cfg, code = _edit.attach_class4(cfg, class_name, "pool", (jen_id, pool_str), mode="guard")
            if code != "ok":
                report.append(f"scope {scope.name}: could not attach class {class_name!r} to its pool ({code})")

        subnets_to_declare[jen_id] = {"name": friendly_name, "cidr": mapped.subnet["subnet"]}

        for res in scope.reservations:
            # v5.28.0 (Q24, F5) — a reservation's own option overrides,
            # mapped the same way scope-level options are; timers (51/
            # 58/59) don't apply to a single reservation, so ignored
            # here same as the policy/server callers.
            option_entries, _timers, opt_warnings = _options_to_kea(res.options, f"reservation {res.ip}")
            report.extend(opt_warnings)
            row = {"subnet-id": jen_id, "hw-address": res.mac, "ip-address": res.ip, "hostname": res.hostname}
            if option_entries:
                row["option-data"] = option_entries
            reservations.append(row)

        report.append(
            f"scope {scope.name}: mapped to subnet {jen_id} ({mapped.subnet['subnet']}), "
            f"{len(mapped.subnet['pools'])} pool(s), {len(mapped.classes)} class(es), "
            f"{len(scope.reservations)} reservation(s)"
        )

    # v5.28.0 (Q24, F6) — option 81 is dropped independently by every
    # scope/reservation/server _options_to_kea() call that sees it;
    # keep only the first of what's otherwise the exact same line
    # repeated once per occurrence.
    seen_81 = False
    deduped_report = []
    for line in report:
        if line == _OPTION_81_WARNING:
            if seen_81:
                continue
            seen_81 = True
        deduped_report.append(line)

    return cfg, reservations, subnets_to_declare, deduped_report
