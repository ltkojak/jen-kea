"""
jen/services/win_dhcp_import.py
─────────────────────────────────
v5.24.0 (Q20) — parse a Windows Server `Export-DhcpServer -File x.xml`
export and map it onto Kea's config shape: subnets from scopes, pools
from ranges minus exclusions, options via Q12's catalog, shared
networks from superscopes, and client classes from the subset of
policies Jen can express as a Kea classification expression.

Two pure stages, matching the rest of this codebase's read/mutate
split:
  * `parse_export(data)` — XML bytes -> a `Plan`, a faithful
    representation of what the export actually contains. Never raises
    on a structurally-valid export missing a section it expects
    (records a warning instead); DOES let defusedxml's own exceptions
    propagate for genuinely malicious XML (entity expansion etc.) — the
    route catches those and flashes, rather than this module pretending
    a parse it refused to even attempt "succeeded" with an empty Plan.
  * `to_kea(plan, existing_dhcp4_cfg, subnet_names, selections)` — the
    Plan, filtered by what the review page's checkboxes selected, onto
    a new Dhcp4 config plus the reservation-add rows and `[subnets]`
    entries the route still needs to push separately (reservations live
    in Kea's host DB via the API, not the config file; subnet names are
    Jen's own, not Kea's).

Deliberately NOT verified against a real Windows export — no maintainer
fixture was available (see PENDING.md's Q20 entry, which pins this
exact fallback). `tests/fixtures/windows-dhcp-export.xml` is authored
from Microsoft's own documented `Export-DhcpServer` XML shape, not
generated by a real DC. Treat option-value byte encodings (especially
the RFC 3442 classless-static-route hex) as reasoned-through rather
than confirmed against genuine output.
"""

