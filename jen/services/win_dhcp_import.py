# ── dataclasses ──────────────────────────────────────────────────────────────


@dataclass
class Policy:
    name: str
    enabled: bool
    processing_order: int
    condition: str  # "AND" | "OR"
    conditions: list[dict] = field(default_factory=list)  # [{"type","operator","value"}]
    ip_ranges: list[tuple[str, str]] = field(default_factory=list)  # [(start, end)]
    options: dict[int, str] = field(default_factory=dict)  # code -> raw joined Value text


@dataclass
class Scope:
    scope_id: str  # Windows' own dotted network address, e.g. "10.0.1.0"
    subnet_mask: str
    name: str
    state: str  # "Active" | "Inactive"
    start_range: str
    end_range: str
    lease_seconds: int
    exclusions: list[tuple[str, str]] = field(default_factory=list)
    options: dict[int, str] = field(default_factory=dict)
    reservations: list[Reservation] = field(default_factory=list)
    policies: list[Policy] = field(default_factory=list)
    superscope_name: str | None = None


@dataclass
class Plan:
    server_options: dict[int, str] = field(default_factory=dict)
    scopes: list[Scope] = field(default_factory=list)
    superscopes: dict[str, list[str]] = field(default_factory=dict)  # name -> [scope_id, ...]
    classes: list[dict] = field(default_factory=list)  # raw <Classes> entries — informational only,
    # see the module docstring / admin-guide: Windows "classes" here are
    # vendor/user-class *registrations*, a different concept from Kea's
    # classification classes (which this module derives from policies
    # instead) — nothing in the pinned spec maps them further, so they're
    # surfaced to the review page as a count + names, not applied.
    warnings: list[str] = field(default_factory=list)


# ── XML helpers (namespace-agnostic, attribute-name tolerant) ───────────────


def _local(tag: str) -> str:
    return tag.rsplit("}", 1)[-1] if "}" in tag else tag


def _children(elem, name: str) -> list:
    if elem is None:
        return []
    name = name.lower()
    return [c for c in elem if _local(c.tag).lower() == name]


def _child(elem, name: str):
    found = _children(elem, name)
    return found[0] if found else None


def _attr(elem, name: str, default: str = "") -> str:
    if elem is None:
        return default
    name = name.lower()
    for k, v in elem.attrib.items():
        if _local(k).lower() == name:
            return v
    return default


def _text(elem) -> str:
    return (elem.text or "").strip() if elem is not None else ""


def _field(elem, name: str, default: str = "") -> str:
    """v5.28.0 (Q24, F1) — the attribute if present (same case/namespace
    tolerance as `_attr`), else the text of the first child element of
    that local name, else `default`. A real `Export-DhcpServer` file
    puts every field in a CHILD ELEMENT (`<Scope><ScopeId>10.10.10.0
    </ScopeId>…`); the hand-authored synthetic fixture used attributes
    (`<Scope ScopeId="…">`) — this reads either shape."""
    if elem is None:
        return default
    attr_val = _attr(elem, name, "")
    if attr_val:
        return attr_val
    child = _child(elem, name)
    if child is not None:
        return _text(child)
    return default


def _bool_field(elem, name: str, default: bool = True) -> bool:
    v = _field(elem, name, "").strip().lower()
    if v in ("true", "1", "yes"):
        return True
    if v in ("false", "0", "no"):
        return False
    return default


def _int_field(elem, name: str, default: int = 0) -> int:
    try:
        return int(_field(elem, name, str(default)))
    except (TypeError, ValueError):
        return default


# ── lease duration ───────────────────────────────────────────────────────────

_DURATION_RE = re.compile(r"^(?:(\d+)\.)?(\d{1,2}):(\d{2}):(\d{2})$")


def _parse_duration(text: str | None, context: str) -> tuple[int, list[str]]:
    """`d.hh:mm:ss` or `hh:mm:ss` -> total seconds. "Unlimited" or
    absent (and anything else unparsable) -> 86400 with a warning."""
    text = (text or "").strip()
    if not text or text.lower() == "unlimited":
        return 86400, [f"{context}: lease duration unlimited/absent — defaulted to 86400s (1 day)"]
    m = _DURATION_RE.match(text)
    if not m:
        return 86400, [f"{context}: unparsable lease duration {text!r} — defaulted to 86400s (1 day)"]
    days, hh, mm, ss = m.groups()
    total = (int(days) if days else 0) * 86400 + int(hh) * 3600 + int(mm) * 60 + int(ss)
    return total, []


# ── classless-static-route (RFC 3442) decoding ──────────────────────────────


def _decode_classless_routes_hex(hex_text: str, context: str) -> tuple[str, list[str]]:
    """The Windows export stores option 121/249 as a single hex-encoded
    RFC 3442 byte string: repeated {mask_len:1}{dest:ceil(mask_len/8)}
    {router:4} until exhausted. Returns Kea's own csv shape
    ("net/prefix - router, ..." — dhcp_options.py's classless-routes
    type) plus any warnings from a malformed tail."""
    warnings: list[str] = []
    body = re.sub(r"[^0-9a-fA-F]", "", hex_text or "")
    if len(body) % 2:
        warnings.append(f"{context}: classless-static-route hex has an odd digit count — last nibble dropped")
        body = body[:-1]
    try:
        raw = bytes.fromhex(body) if body else b""
    except ValueError:
        return "", [f"{context}: classless-static-route hex could not be decoded"]
    routes = []
    i = 0
    while i < len(raw):
        mask_len = raw[i]
        i += 1
        if mask_len > 32:
            warnings.append(f"{context}: classless-static-route mask length {mask_len} is invalid — stopped decoding")
            break
        needed = (mask_len + 7) // 8
        if i + needed + 4 > len(raw):
            warnings.append(f"{context}: classless-static-route entry is truncated — stopped decoding")
            break
        dest_octets = list(raw[i : i + needed]) + [0] * (4 - needed)
        i += needed
        router_octets = raw[i : i + 4]
        i += 4
        dest = ".".join(str(b) for b in dest_octets)
        router = ".".join(str(b) for b in router_octets)
        routes.append(f"{dest}/{mask_len} - {router}")
    return ", ".join(routes), warnings


# ── option values ────────────────────────────────────────────────────────────


def _parse_option_values(elem, context: str) -> tuple[dict[int, str], list[str]]:
    """<OptionValues><OptionValue OptionId="N"><Value>...</Value>...
    -> {code: raw joined text}. Multiple <Value> children join with
    ", " (Windows' shape for a multi-valued option); 121/249 are
    collapsed to a single <Value> hex string and decoded separately
    below, once the option's actual type is known. v5.28.0 (Q24, F6) —
    an OptionValue scoped to a vendor or user class (a non-empty
    <VendorClass>/<UserClass>) is skipped: Kea models that as a client
    class's own option-data, not a plain per-subnet/global value, and
    silently writing it as one would apply it to every client."""
    out: dict[int, str] = {}
    warnings: list[str] = []
    for ov in _children(elem, "OptionValue"):
        try:
            code = int(_field(ov, "OptionId"))
        except ValueError:
            warnings.append(f"{context}: OptionValue with a non-numeric OptionId — skipped")
            continue
        if _field(ov, "VendorClass") or _field(ov, "UserClass"):
            warnings.append(
                f"{context}: vendor/user-class-scoped option {code} not imported (Kea models these as client classes)"
            )
            continue
        values = [_text(v) for v in _children(ov, "Value")]
        out[code] = ", ".join(v for v in values if v)
    return out, warnings


_OPTION_81_WARNING = "option 81 (client FQDN flags) is DDNS behaviour, not option-data — configure it on the DDNS page"

# v5.28.0 (Q24, F6) — codes _options_to_kea handles itself, before the
# catalog lookup: 51/58/59 become lease timers (scope_to_subnet merges
# them into the subnet block), 81 is dropped outright (DDNS behavior,
# not an option). Never reach the generic per-code catalog/validate path.
_TIMER_CODES = {51: "valid-lifetime", 58: "renew-timer", 59: "rebind-timer"}


def _options_to_kea(raw_options: dict[int, str], context: str) -> tuple[list[dict], dict[str, str], list[str]]:
    """Raw Windows option values -> (Kea option-data entries, lease
    timers, warnings), via Q12's catalog. 249 (Microsoft's own
    classless-static-route code) is folded into 121. Unknown codes and
    values that fail Q12's own validate() are skipped with a warning,
    never written unvalidated. `timers` is a subset of {"valid-lifetime",
    "renew-timer", "rebind-timer"} — callers that don't have a lease
    duration to compare against (policies, server/global options,
    reservations) simply ignore it."""
    warnings: list[str] = []
    merged: dict[int, str] = {}
    for code, raw in raw_options.items():
        real_code = code
        if code == 249:
            if 121 in raw_options:
                warnings.append(f"{context}: option 249 present alongside 121 — 249 ignored")
                continue
            real_code = 121
            warnings.append(f"{context}: option 249 (Microsoft classless-static-route) converted to standard 121")
        if real_code in merged:
            warnings.append(f"{context}: duplicate option {real_code} — first value kept")
            continue
        merged[real_code] = raw

    timers: dict[str, str] = {}
    entries = []
    for code, raw in merged.items():
        if code == 81:
            if _OPTION_81_WARNING not in warnings:
                warnings.append(_OPTION_81_WARNING)
            continue
        if code in _TIMER_CODES:
            timers[_TIMER_CODES[code]] = raw
            continue
        opt_type = _opts.type_for(code)
        if opt_type is None:
            warnings.append(f"{context}: skipped option {code} (not in Jen's catalog)")
            continue
        if opt_type == "classless-routes":
            data, decode_warnings = _decode_classless_routes_hex(raw, context)
            warnings.extend(decode_warnings)
            if not data:
                continue
        else:
            data = raw
        err = _opts.validate(opt_type, data)
        if err:
            warnings.append(f"{context}: skipped option {code} ({_opts.V4_OPTIONS[code]['name']}) — {err}")
            continue
        entries.append(
            {
                "name": _opts.V4_OPTIONS[code]["name"],
                "code": code,
                "space": "dhcp4",
                "csv-format": True,
                "data": _opts.normalize(opt_type, data),
            }
        )
    return entries, timers, warnings


# ── reservations ─────────────────────────────────────────────────────────────

_CLIENT_ID_RE = re.compile(r"^[0-9a-fA-F]{2}([:-][0-9a-fA-F]{2}){5}$")


@dataclass
class Reservation:
    mac: str
    ip: str
    hostname: str
    options: dict[int, str] = field(default_factory=dict)  # v5.28.0 (Q24, F5)


def _sanitize_hostname(name: str) -> str:
    """v5.28.0 (Q24, F4) — a Windows reservation name is free text
    ("Smart Plug 7", with a domain suffix or not); turn it into
    something `valid_hostname` can accept before ever calling it,
    rather than only trying the raw text and giving up."""
    sanitized = re.sub(r"[^A-Za-z0-9.-]+", "-", name)
    sanitized = re.sub(r"-{2,}", "-", sanitized)
    return sanitized.strip("-.")


def _parse_reservations(elem, context: str) -> tuple[list[Reservation], list[str]]:
    """`Type` `Dhcp` AND `Both` are imported (v5.28.0, Q24, F4) — `Both`
    is "DHCP and BOOTP", Windows' own default, and Kea only speaks
    DHCP, so it's just a reservation to us. Only `Bootp` is skipped."""
    out = []
    warnings = []
    for r in _children(elem, "Reservation"):
        rtype = _field(r, "Type", "Dhcp")
        ip = _field(r, "IPAddress")
        client_id = _field(r, "ClientId")
        name = _field(r, "Name")
        if rtype.lower() == "bootp":
            warnings.append(f"{context}: reservation {ip or '?'}: BOOTP-only — not imported")
            continue
        if not _CLIENT_ID_RE.match(client_id or ""):
            n_bytes = len(re.split(r"[:-]", client_id)) if client_id else 0
            warnings.append(
                f"{context}: reservation {name or ip or '?'} ({ip or '?'}) uses a {n_bytes}-byte client "
                "identifier, not a MAC — Kea needs a `client-id` reservation for it; add it by hand after "
                "the import"
            )
            continue
        mac = client_id.replace("-", ":").lower()
        if not _auth.valid_ip(ip):
            warnings.append(f"{context}: reservation for {mac} has an invalid IP {ip!r} — skipped")
            continue
        if name:
            sanitized = _sanitize_hostname(name)
            if _auth.valid_hostname(sanitized):
                name = sanitized
            else:
                warnings.append(
                    f"{context}: reservation {ip} hostname {name!r} failed validation — imported without it"
                )
                name = ""
        options, opt_warnings = _parse_option_values(_child(r, "OptionValues"), f"{context} reservation {ip}")
        warnings.extend(opt_warnings)
        out.append(Reservation(mac=mac, ip=ip, hostname=name, options=options))
    return out, warnings


# ── policies ─────────────────────────────────────────────────────────────────


def _parse_policies(elem, context: str) -> tuple[list[Policy], list[str]]:
    out = []
    warnings = []
    for p in _children(elem, "Policy"):
        name = _field(p, "Name")
        conditions = []
        for c in _children(_child(p, "Conditions"), "Condition"):
            conditions.append(
                {
                    "type": _field(c, "Type"),
                    "operator": _field(c, "Operator", "Equals"),
                    "value": _field(c, "Value"),
                }
            )
        ip_ranges = []
        for r in _children(_child(p, "IPRanges"), "IPRange"):
            ip_ranges.append((_field(r, "StartRange"), _field(r, "EndRange")))
        options, opt_warnings = _parse_option_values(_child(p, "OptionValues"), f"{context} policy {name}")
        warnings.extend(opt_warnings)
        out.append(
            Policy(
                name=name,
                enabled=_bool_field(p, "Enabled", True),
                processing_order=_int_field(p, "ProcessingOrder", 0),
                condition=_field(p, "Condition", "AND").upper(),
                conditions=conditions,
                ip_ranges=ip_ranges,
                options=options,
            )
        )
    return out, warnings


# ── scopes ───────────────────────────────────────────────────────────────────


def _parse_scope(elem) -> tuple[Scope | None, list[str]]:
    scope_id = _field(elem, "ScopeId")
    name = _field(elem, "Name") or scope_id
    context = f"scope {name} ({scope_id})"
    warnings: list[str] = []

    # v5.28.0 (Q24, F3) — never let a scope with a missing/invalid
    # required field reach the pool math (scope_to_subnet's IP
    # arithmetic on an empty string raises AddressValueError, which
    # used to 500 the review page).
    subnet_mask = _field(elem, "SubnetMask")
    start_range = _field(elem, "StartRange")
    end_range = _field(elem, "EndRange")
    for field_name, value, valid in (
        ("ScopeId", scope_id, _auth.valid_ip(scope_id)),
        ("SubnetMask", subnet_mask, _auth.valid_ip(subnet_mask)),
        ("StartRange", start_range, _auth.valid_ip(start_range)),
        ("EndRange", end_range, _auth.valid_ip(end_range)),
    ):
        if not value or not valid:
            warnings.append(f"scope {name}: missing/invalid {field_name} — skipped")
            return None, warnings

    lease_seconds, dur_warnings = _parse_duration(_field(elem, "LeaseDuration"), context)
    warnings.extend(dur_warnings)

    exclusions = []
    for r in _children(_child(elem, "ExclusionRanges"), "IPRange"):
        exclusions.append((_field(r, "StartRange"), _field(r, "EndRange")))

    reservations, res_warnings = _parse_reservations(_child(elem, "Reservations"), context)
    warnings.extend(res_warnings)

    options, opt_warnings = _parse_option_values(_child(elem, "OptionValues"), context)
    warnings.extend(opt_warnings)

    policies, policy_warnings = _parse_policies(_child(elem, "Policies"), context)
    warnings.extend(policy_warnings)

    scope = Scope(
        scope_id=scope_id,
        subnet_mask=subnet_mask,
        name=name,
        state=_field(elem, "State", "Active"),
        start_range=start_range,
        end_range=end_range,
        lease_seconds=lease_seconds,
        exclusions=exclusions,
        options=options,
        reservations=reservations,
        policies=policies,
        superscope_name=_field(elem, "SuperscopeName") or None,
    )
    if scope.state.lower() != "active":
        warnings.append(f"{context}: scope is Inactive in Windows — imported, unticked by default")
    return scope, warnings


def _parse_superscopes(elem) -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for sc in _children(elem, "Superscope"):
        name = _field(sc, "Name")
        ids = [_text(s) for s in _children(sc, "ScopeId") if _text(s)]
        if name:
            out[name] = ids
    return out


def _parse_classes(elem) -> list[dict]:
    out = []
    for c in _children(elem, "Class"):
        out.append({"name": _field(c, "Name"), "type": _field(c, "Type")})
    return out


# ── top level ────────────────────────────────────────────────────────────────


def parse_export(data: bytes) -> Plan:
    """`Export-DhcpServer -File x.xml`'s bytes -> a Plan. Raises
    whatever defusedxml raises on genuinely malicious XML (entity
    expansion, external references) — the caller decides how to
    present that; anything else missing or malformed inside an
    otherwise well-formed document is recorded as a warning instead."""
    root = _ET.fromstring(data)
    plan = Plan()

    ipv4 = None
    for child in root:
        if _local(child.tag).lower() == "ipv4":
            ipv4 = child
            break
    if ipv4 is None:
        plan.warnings.append("No <IPv4> section found in the export — nothing to import.")
        return plan

    server_options, opt_warnings = _parse_option_values(_child(ipv4, "OptionValues"), "server")
    plan.server_options = server_options
    plan.warnings.extend(opt_warnings)

    scopes_elem = _child(ipv4, "Scopes")
    for scope_elem in _children(scopes_elem, "Scope"):
        scope, scope_warnings = _parse_scope(scope_elem)
        plan.warnings.extend(scope_warnings)
        if scope is not None:
            plan.scopes.append(scope)

    plan.superscopes = _parse_superscopes(_child(ipv4, "Superscopes"))
    # v5.28.0 (Q24, F2) — the real export carries superscope membership
    # on the SCOPE itself (<SuperScopeName>), not (only) in a top-level
    # <Superscopes> list — keep reading that too, a different server
    # version may still emit it.
    for scope in plan.scopes:
        if scope.superscope_name:
            members = plan.superscopes.setdefault(scope.superscope_name, [])
            if scope.scope_id not in members:
                members.append(scope.scope_id)
    plan.classes = _parse_classes(_child(ipv4, "Classes"))

    if not plan.scopes:
        plan.warnings.append("No scopes found in the export.")

    # v5.28.0 (Q24, F7) — cheap honesty lines for things the real export
    # exposed that this importer has never claimed to handle.
    filters = _child(ipv4, "Filters")
    if filters is not None and (_bool_field(filters, "Allow", False) or _bool_field(filters, "Deny", False)):
        filter_entries = _children(filters, "Filter")
        allow_count = sum(1 for f in filter_entries if _field(f, "List", "").lower() == "allow")
        deny_count = sum(1 for f in filter_entries if _field(f, "List", "").lower() == "deny")
        plan.warnings.append(
            f"MAC allow/deny filtering is enabled in Windows ({allow_count} allow / {deny_count} deny entries) "
            "— not imported; Kea's equivalent is a client class"
        )

    ipv6 = None
    for child in root:
        if _local(child.tag).lower() == "ipv6":
            ipv6 = child
            break
    if ipv6 is not None and _children(_child(ipv6, "Scopes"), "Scope"):
        plan.warnings.append("IPv6 scopes are not imported (IPv4 only)")

    return plan


# ── pool math ────────────────────────────────────────────────────────────────


def _ip2int(s: str) -> int:
    return int(ipaddress.IPv4Address(s))


def _int2ip(i: int) -> str:
    return str(ipaddress.IPv4Address(i))


def split_pool_by_exclusions(start: str, end: str, exclusions: list[tuple[str, str]]) -> list[tuple[int, int]]:
    """[start, end] minus each exclusion, as a list of (start_int, end_int)
    sub-ranges (integers so the pool-carving below can keep splitting
    without repeated string<->int round trips). An exclusion covering
    the whole range legitimately yields an empty list — a
    reservation-only subnet is valid in Kea (Gotcha in PENDING.md)."""
    segments = [(_ip2int(start), _ip2int(end))]
    for exc_start, exc_end in exclusions:
        if not exc_start or not exc_end:
            continue
        es, ee = _ip2int(exc_start), _ip2int(exc_end)
        new_segments = []
        for seg_s, seg_e in segments:
            if ee < seg_s or es > seg_e:
                new_segments.append((seg_s, seg_e))
                continue
            if es > seg_s:
                new_segments.append((seg_s, es - 1))
            if ee < seg_e:
                new_segments.append((ee + 1, seg_e))
        segments = new_segments
    return [(s, e) for s, e in segments if s <= e]


def _carve_pool(segments: list[tuple[int, int]], want_start: int, want_end: int) -> tuple[list[tuple[int, int]], bool]:
    """Remove [want_start, want_end] from whichever segment fully
    contains it, replacing that one segment with up to two remaining
    pieces. Returns (new_segments, carved_ok) — carved_ok is False (segments
    unchanged) when the requested range doesn't sit entirely inside a
    single existing segment (split across exclusions, outside the pool
    entirely, or overlapping two policies)."""
    for i, (seg_s, seg_e) in enumerate(segments):
        if seg_s <= want_start and want_end <= seg_e:
            out = segments[:i] + segments[i + 1 :]
            if seg_s < want_start:
                out.append((seg_s, want_start - 1))
            if want_end < seg_e:
                out.append((want_end + 1, seg_e))
            return out, True
    return segments, False


# ── policies -> Kea client classes ──────────────────────────────────────────

_WINDOWS_CONDITION_FIELDS = {
    "vendorclass": "vendor_class",
    "userclass": "user_class",
    "clientid": "client_id",
    "relayagentinformation": "circuit_id",
}


def _sanitize_class_name(name: str) -> str:
    sanitized = re.sub(r"[^A-Za-z0-9_-]", "_", name or "")
    if not sanitized or not sanitized[0].isalpha():
        sanitized = "policy_" + sanitized
    return sanitized[:64]


def _condition_to_rule(cond: dict, context: str) -> tuple[dict | None, str | None]:
    """(rule, None) or (None, warning). MACAddress with a trailing `*`
    and a 3-byte prefix maps to mac_oui; a full 6-byte value (wildcard
    or not) maps to mac."""
    ctype = (cond.get("type") or "").strip().lower()
    value = cond.get("value") or ""
    if ctype == "macaddress":
        stripped = value.rstrip("*")
        hex_only = re.sub(r"[:\-]", "", stripped)
        field_name = "mac_oui" if value.endswith("*") and len(hex_only) == 6 else "mac"
        return {"field": field_name, "op": "equals", "value": stripped}, None
    field_name = _WINDOWS_CONDITION_FIELDS.get(ctype)
    if field_name is None:
        return None, f"{context}: condition type {cond.get('type')!r} is not supported"
    return {"field": field_name, "op": "equals", "value": value}, None


def policy_to_class(policy: Policy, context: str) -> tuple[dict | None, list[str]]:
    """A Policy -> a Kea client-class dict ({"name", "test", possibly
    "option-data"}), or None with the warning explaining why it can't
    be expressed. Never raises."""
    warnings: list[str] = []
    label = f"{context} policy {policy.name!r}"
    if not policy.enabled:
        warnings.append(f"{label}: disabled in Windows — not imported")
        return None, warnings
    if not policy.conditions:
        warnings.append(f"{label}: has no conditions — not imported")
        return None, warnings

    operators = {(c.get("operator") or "Equals").strip().lower() for c in policy.conditions}
    negate = False
    if operators == {"notequals"}:
        if len(policy.conditions) > 1:
            warnings.append(f"{label}: NotEquals is only supported on a single-condition policy — not imported")
            return None, warnings
        negate = True
    elif "notequals" in operators:
        warnings.append(f"{label}: mixes Equals and NotEquals conditions — not imported")
        return None, warnings

    rules = []
    for cond in policy.conditions:
        rule, warning = _condition_to_rule(cond, label)
        if warning:
            warnings.append(f"{warning} — policy not imported")
            return None, warnings
        rules.append(rule)

    combinator = "any" if policy.condition == "OR" else "all"
    try:
        expr = _classes.build_expression(rules, combinator=combinator, negate=negate)
    except ValueError as e:
        warnings.append(f"{label}: not imported: {e}")
        return None, warnings

    name = policy.name
    if not _auth.valid_class_name(name):
        sanitized = _sanitize_class_name(name)
        warnings.append(f"{label}: name sanitized to {sanitized!r} for Kea")
        name = sanitized

    class_dict = {"name": name, "test": expr}
    if policy.options:
        option_entries, _timers, opt_warnings = _options_to_kea(policy.options, label)
        warnings.extend(opt_warnings)
        if option_entries:
            class_dict["option-data"] = option_entries
    return class_dict, warnings


